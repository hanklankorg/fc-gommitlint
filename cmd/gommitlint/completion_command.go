const (
	shellBash     = "bash"
	shellZsh      = "zsh"
	shellFish     = "fish"
	completionAll = "all"
)

var (
	errCompletionMissingShell = errors.New("missing shell for completion command")
	errCompletionAllExtraArgs = errors.New("no extra arguments allowed with --all")
	errCompletionExtraArgs    = errors.New("exactly one shell argument is required")
	errCompletionOutput       = errors.New("failed to write completion output")
	errCompletionUnknownShell = errors.New("unknown shell")
)

const bashCompletionTemplate = `
# This is a shell completion script auto-generated by https://github.com/urfave/cli for bash.

# Macs have bash3 for which the bash-completion package doesn't include
# _init_completion. This is a minimal version of that function.
__%[1]s_init_completion() {
  COMPREPLY=()
  _get_comp_words_by_ref "$@" cur prev words cword
}

__%[1]s_bash_autocomplete() {
  if [[ "${COMP_WORDS[0]}" != "source" ]]; then
    local cur opts words
    COMPREPLY=()
    cur="${COMP_WORDS[COMP_CWORD]}"
    if declare -F _init_completion >/dev/null 2>&1; then
      _init_completion -n "=:" || return
    else
      __%[1]s_init_completion -n "=:" || return
    fi
    words=("${words[@]:0:$cword}")
    if [[ "$cur" == "-"* ]]; then
      opts=$(%[2]s=bash "${words[@]}" "${cur}" --generate-shell-completion 2>/dev/null)
    else
      opts=$(%[2]s=bash "${words[@]}" --generate-shell-completion 2>/dev/null)
    fi
    if [[ -z "$opts" ]]; then
      COMPREPLY=($(compgen -f -- "${cur}"))
      return 0
    fi
    COMPREPLY=($(compgen -W "${opts}" -- "${cur}"))
    return 0
  fi
}

complete -o bashdefault -o default -o nospace -F __%[1]s_bash_autocomplete %[1]s
`

const zshCompletionTemplate = `compdef _%[1]s %[1]s

# This is a shell completion script auto-generated by https://github.com/urfave/cli for zsh.

_%[1]s() {
	local -a opts # Declare a local array
	local current
	current=${words[-1]} # -1 means "the last element"
	if [[ "$current" == "-"* ]]; then
		# Current word starts with a hyphen, so complete flags/options
		opts=("${(@f)$(%[2]s=zsh ${words[@]:0:#words[@]-1} ${current} --generate-shell-completion)}")
	else
		# Current word does not start with a hyphen, so complete subcommands
		opts=("${(@f)$(%[2]s=zsh ${words[@]:0:#words[@]-1} --generate-shell-completion)}")
	fi

	if [[ "${opts[1]}" != "" ]]; then
		_describe 'values' opts
	else
		_files
	fi
}

# Don't run the completion function when being source-ed or eval-ed.
# See https://github.com/urfave/cli/issues/1874 for discussion.
if [ "$funcstack[1]" = "_%[1]s" ]; then
	_%[1]s
fi
`

func configureCompletionCommand(completion *cli.Command, localizer output.Localizer) {
	localizer = output.EnsureLocalizer(localizer)
	// urfave v3.10 adds one output-only subcommand per shell. Gommitlint's
	// parent action owns both installation and --stdout rendering, so retaining
	// those children would bypass that contract for `completion <shell>`.
	completion.Commands = nil
	completion.Hidden = false
	completion.Usage = localizer.Get("install shell completion script")
	completion.Description = localizer.Get("Installs shell completion for bash, zsh, or fish. Use --all to install all supported shells.")
	completion.ArgsUsage = "bash|zsh|fish"
	completion.Flags = []cli.Flag{
		&cli.BoolFlag{
			Name:  completionAll,
			Usage: localizer.Get("install completions for all supported shells"),
		},
		&cli.BoolFlag{
			Name:  "stdout",
			Usage: localizer.Get("write the completion script to stdout instead of installing it"),
		},
	}
	completion.ShellComplete = shellCompleteWithValues
	completion.Action = completionAction(localizer)
	completion.ArgsUsage = "bash|zsh|fish [--stdout]"
}

func completionAction(localizer output.Localizer) cli.ActionFunc {
	return func(ctx context.Context, cmd *cli.Command) error {
		if completionWantsHelp(cmd) {
			return cli.ShowCommandHelp(ctx, cmd.Root(), cmd.Name)
		}

		args := cmd.Args()
		toStdout := cmd.Bool("stdout") || completionHasStdoutArg(args)

		shells, err := completionShellTargets(cmd, args)
		if err != nil {
			return completionRecoveryError(localizer, cmd.Root().Name, err)
		}

		if toStdout {
			return outputCompletionScripts(cmd, localizer, shells)
		}

		return installCompletionScripts(cmd, localizer, shells)
	}
}

func completionHasStdoutArg(args cli.Args) bool {
	for i := range args.Len() {
		if args.Get(i) == flagStdoutLong {
			return true
		}
	}

	return false
}

func completionWantsHelp(cmd *cli.Command) bool {
	args := cmd.Args()
	if cmd.Bool("help") || cmd.Bool("h") {
		return true
	}

	if args.Len() == 0 {
		return false
	}

	firstArg := args.Get(0)

	return firstArg == "-h" || firstArg == flagHelpLong
}

func installCompletionScripts(cmd *cli.Command, localizer output.Localizer, shells []string) error {
	appName := completionAppName(cmd)
	for _, shell := range shells {
		script, err := renderCompletionScript(cmd, shell, appName)
		if err != nil {
			return completionRecoveryError(localizer, cmd.Root().Name, err)
		}

		installPath, err := completionInstallPath(shell, appName)
		if err != nil {
			return completionRecoveryError(localizer, cmd.Root().Name, err)
		}

		existed := fileExists(installPath)
		if err := writeCompletionFile(installPath, []byte(script)); err != nil {
			return completionRecoveryError(localizer, cmd.Root().Name, err)
		}

		printCompletionInstallMessage(cmd, localizer, shell, installPath, existed)
	}

	return nil
}

func outputCompletionScripts(cmd *cli.Command, localizer output.Localizer, shells []string) error {
	appName := completionAppName(cmd)
	for _, shell := range shells {
		script, err := renderCompletionScript(cmd, shell, appName)
		if err != nil {
			return completionRecoveryError(localizer, cmd.Root().Name, err)
		}

		if _, err := fmt.Fprint(cmd.Writer, script); err != nil {
			cause := errors.Join(commands.ErrOutputWrite, errCompletionOutput, err)

			return completionRecoveryError(localizer, cmd.Root().Name, cause)
		}
	}

	return nil
}

func completionAppName(cmd *cli.Command) string {
	rootName := cmd.Root().Name
	if !isSafeCompletionAppName(rootName) {
		rootName = appName
	}

	binaryName := filepath.Base(os.Args[0])
	if !isSafeCompletionAppName(binaryName) {
		return rootName
	}

	return binaryName
}

func isSafeCompletionAppName(name string) bool {
	for index := range len(name) {
		char := name[index]
		if char >= 'a' && char <= 'z' || char >= 'A' && char <= 'Z' || char >= '0' && char <= '9' || char == '_' {
			continue
		}

		if index > 0 && (char == '-' || char == '.') {
			continue
		}

		return false
	}

	return name != ""
}

func completionShellTargets(cmd *cli.Command, args cli.Args) ([]string, error) {
	// Filter out --stdout and --all from args to get just shell names
	var shellArgs []string

	for i := range args.Len() {
		arg := args.Get(i)
		if arg == flagStdoutLong || arg == flagAllLong {
			continue
		}

		shellArgs = append(shellArgs, arg)
	}

	// Check for --all flag (either as flag or argument)
	if cmd.Bool(completionAll) || completionHasAllArg(args) {
		if len(shellArgs) > 0 {
			return nil, fmt.Errorf("%w", errCompletionAllExtraArgs)
		}

		return completionShells(), nil
	}

	if len(shellArgs) == 0 {
		return nil, fmt.Errorf("%w", errCompletionMissingShell)
	}

	firstArg := shellArgs[0]
	if firstArg == completionAll {
		if len(shellArgs) > 1 {
			return nil, fmt.Errorf("%w", errCompletionAllExtraArgs)
		}

		return completionShells(), nil
	}

	if len(shellArgs) > 1 {
		return nil, fmt.Errorf("%w", errCompletionExtraArgs)
	}

	return []string{firstArg}, nil
}

func completionHasAllArg(args cli.Args) bool {
	for i := range args.Len() {
		if args.Get(i) == flagAllLong {
			return true
		}
	}

	return false
}

func renderCompletionScript(cmd *cli.Command, shell string, appName string) (string, error) {
	switch shell {
	case shellBash:
		return fmt.Sprintf(bashCompletionTemplate, appName, completionShellEnv), nil
	case shellZsh:
		return fmt.Sprintf(zshCompletionTemplate, appName, completionShellEnv), nil
	case shellFish:
		return renderFishCompletion(cmd, appName)
	default:
		return "", fmt.Errorf("%w: %s", errCompletionUnknownShell, shell)
	}
}

func renderFishCompletion(cmd *cli.Command, appName string) (string, error) {
	restore := hideCompletionCommands(cmd.Root())
	base, err := cmd.Root().ToFishCompletion()

	restore()

	if err != nil {
		return "", err
	}

	if appName != cmd.Root().Name {
		base = rewriteFishAppName(base, cmd.Root().Name, appName)
	}

	content := fishDynamicCompletionDefinition(appName) + base
	content = applyFishValueCompletions(content, appName)
	content = applyFishFileCompletions(content)
	content = appendFishGlobalFlagCompletions(content, appName, cmd.Root())
	content = appendFishPositionalCompletions(content, appName)

	return content, nil
}

func hideCompletionCommands(root *cli.Command) func() {
	type commandChildren struct {
		command  *cli.Command
		children []*cli.Command
	}

	saved := make([]commandChildren, 0)

	var filter func(*cli.Command)

	filter = func(command *cli.Command) {
		saved = append(saved, commandChildren{command: command, children: command.Commands})
		visible := make([]*cli.Command, 0, len(command.Commands))

		for _, child := range command.Commands {
			if child.Hidden {
				continue
			}

			visible = append(visible, child)
			filter(child)
		}

		command.Commands = visible
	}

	filter(root)

	return func() {
		for _, entry := range saved {
			entry.command.Commands = entry.children
		}
	}
}

func appendFishGlobalFlagCompletions(content string, appName string, root *cli.Command) string {
	lines := strings.Split(content, "\n")
	noSubcommand := fishNoSubcommandFunction(appName)
	globalFlags := make(map[string]struct{}, len(root.Flags))

	for _, flag := range root.Flags {
		for _, name := range flag.Names() {
			globalFlags[strings.TrimSpace(name)] = struct{}{}
		}
	}

	condition := fishAnySubcommandCondition(root)
	if condition == "" {
		return content
	}

	var duplicates []string

	for _, line := range lines {
		if !strings.Contains(line, " -l ") {
			continue
		}

		if !strings.Contains(line, noSubcommand) {
			continue
		}

		flagName := fishFlagNameFromLine(line)
		if flagName == "" {
			continue
		}

		if _, ok := globalFlags[flagName]; !ok {
			continue
		}

		duplicate := strings.Replace(line, noSubcommand, condition, 1)
		duplicates = append(duplicates, duplicate)
	}

	if len(duplicates) == 0 {
		return content
	}

	return strings.Join([]string{content, strings.Join(duplicates, "\n"), ""}, "\n")
}

func fishAnySubcommandCondition(root *cli.Command) string {
	var names []string

	for _, command := range root.VisibleCommands() {
		if command.Name == commandHelp {
			continue
		}

		names = append(names, command.Names()...)
	}

	slices.Sort(names)
	names = slices.Compact(names)

	if len(names) == 0 {
		return ""
	}

	return "__fish_seen_subcommand_from " + strings.Join(names, " ")
}

func fishFlagNameFromLine(line string) string {
	marker := " -l "

	start := strings.Index(line, marker)
	if start == -1 {
		return ""
	}

	start += len(marker)
	remainder := line[start:]

	before, _, ok := strings.Cut(remainder, " ")
	if !ok {
		return remainder
	}

	return before
}

func applyFishFileCompletions(content string) string {
	flags := completionFileFlags()

	lines := strings.Split(content, "\n")
	for lineIndex, line := range lines {
		for _, flagName := range flags {
			if !strings.Contains(line, " -l "+flagName) {
				continue
			}

			if strings.Contains(line, " -F") {
				break
			}

			switch {
			case strings.Contains(line, " -f "):
				line = strings.Replace(line, " -f ", " -F ", 1)
			case strings.HasSuffix(line, " -f"):
				line = strings.TrimSuffix(line, " -f") + " -F"
			default:
				line += " -F"
			}

			lines[lineIndex] = line

			break
		}
	}

	return strings.Join(lines, "\n")
}

func appendFishPositionalCompletions(content string, appName string) string {
	line := fmt.Sprintf("complete -c %s -n '__fish_seen_subcommand_from completion' -f -a '%s'",
		appName,
		strings.Join(completionShells(), " "),
	)

	return strings.Join([]string{content, line, ""}, "\n")
}

type fishValueCompletionUpdate struct {
	condition string
	flag      string
	values    []string
	dynamic   bool
}

func applyFishValueCompletions(content string, appName string) string {
	updates := fishValueCompletionUpdates(appName)
	if len(updates) == 0 {
		return content
	}

	lines := strings.Split(content, "\n")
	for lineIndex, line := range lines {
		if strings.TrimSpace(line) == "" {
			continue
		}

		for _, update := range updates {
			arguments := fishCompletionArguments(appName, update)
			if arguments == "" {
				continue
			}

			if fishFlagNameFromLine(line) != update.flag {
				continue
			}

			if update.condition != "" && !strings.Contains(line, update.condition) {
				continue
			}

			if strings.Contains(line, " -a '") {
				break
			}

			lines[lineIndex] = line + " -a '" + arguments + "'"

			break
		}
	}

	return strings.Join(lines, "\n")
}

func fishCompletionArguments(appName string, update fishValueCompletionUpdate) string {
	if update.dynamic {
		return fmt.Sprintf("(%s %s)", fishDynamicCompletionFunction(appName), update.flag)
	}

	values := make([]string, len(update.values))
	for index, value := range update.values {
		value = strings.ReplaceAll(value, `\`, `\\`)
		values[index] = strings.ReplaceAll(value, `'`, `\'`)
	}

	return strings.Join(values, " ")
}

// Fish expands the repository argument list as distinct argv elements without
// evaluating shell syntax in the path supplied on the active command line.
func fishDynamicCompletionDefinition(appName string) string {
	return fmt.Sprintf(`function %s
    set -l tokens (commandline -opc)
    set -l repository_args
    set -l index 1

    while test $index -le (count $tokens)
        switch $tokens[$index]
            case '--%s'
                if test $index -lt (count $tokens)
                    set repository_args --%s $tokens[(math $index + 1)]
                end
            case '--%s=*'
                set repository_args --%s (string replace -- '--%s=' '' $tokens[$index])
        end
        set index (math $index + 1)
    end

    env %s=%s %s $repository_args %s --$argv[1] --generate-shell-completion 2>/dev/null
end

`, fishDynamicCompletionFunction(appName), flags.RepoPath, flags.RepoPath, flags.RepoPath,
		flags.RepoPath, flags.RepoPath, completionShellEnv, shellFish, appName, commandValidate)
}

func fishDynamicCompletionFunction(appName string) string {
	return "__fish_" + strings.NewReplacer("-", "_", ".", "_").Replace(appName) + "_dynamic_completion"
}

func fishValueCompletionUpdates(appName string) []fishValueCompletionUpdate {
	noSubcommand := fishNoSubcommandFunction(appName)

	ruleNames := configTypes.GetValidRuleNames()
	slices.Sort(ruleNames)

	return []fishValueCompletionUpdate{
		{condition: noSubcommand, flag: flags.Theme, values: output.SupportedThemes()},
		{condition: noSubcommand, flag: flags.Color, values: cliadapter.SupportedColorSettings()},
		{condition: noSubcommand, flag: flags.LogLevel, values: logadapter.LogLevelNames()},
		{condition: fishValidateCondition, flag: flags.Format, values: output.SupportedFormats()},
		{condition: fishValidateCondition, flag: flags.BaseBranch, dynamic: true},
		{condition: fishValidateCondition, flag: flags.Ref, dynamic: true},
		{condition: fishValidateCondition, flag: flags.Range, dynamic: true},
		{condition: fishValidateCondition, flag: flags.Rule, values: ruleNames},
		{condition: fishValidateCondition, flag: flags.ExcludeRule, values: ruleNames},
		{condition: fishValidateCondition, flag: flags.RuleHelp, values: ruleNames},
		{condition: fishConfigShowCondition, flag: flags.Format, values: []string{output.FormatText, output.FormatJSON, "yaml"}},
	}
}

func rewriteFishAppName(content string, originalName string, appName string) string {
	originalFunc := fishNoSubcommandFunction(originalName)
	replacementFunc := fishNoSubcommandFunction(appName)
	content = strings.ReplaceAll(content, originalFunc, replacementFunc)
	content = strings.ReplaceAll(content, "-c "+originalName, "-c "+appName)
	content = strings.ReplaceAll(content, "("+originalName+" ", "("+appName+" ")
	content = strings.ReplaceAll(content, "'"+originalName+"'", "'"+appName+"'")

	return content
}

func fishNoSubcommandFunction(appName string) string {
	return "__fish_" + strings.ReplaceAll(appName, "-", "_") + "_no_subcommand"
}

func completionInstallPath(shell string, appName string) (string, error) {
	switch shell {
	case shellBash:
		dataHome, err := completionDataHome()
		if err != nil {
			return "", err
		}

		return filepath.Join(dataHome, "bash-completion", "completions", appName), nil
	case shellZsh:
		dataHome, err := completionDataHome()
		if err != nil {
			return "", err
		}

		return filepath.Join(dataHome, "zsh", "completions", "_"+appName), nil
	case shellFish:
		configHome, err := completionConfigHome()
		if err != nil {
			return "", err
		}

		return filepath.Join(configHome, "fish", "completions", appName+".fish"), nil
	default:
		return "", fmt.Errorf("%w: %s", errCompletionUnknownShell, shell)
	}
}

func completionDataHome() (string, error) {
	if dataHome := os.Getenv("XDG_DATA_HOME"); dataHome != "" {
		return dataHome, nil
	}

	return userHomeJoin(".local", "share")
}

func completionConfigHome() (string, error) {
	if configHome := os.Getenv("XDG_CONFIG_HOME"); configHome != "" {
		return configHome, nil
	}

	return userHomeJoin(".config")
}

func userHomeJoin(parts ...string) (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", err
	}

	return filepath.Join(append([]string{home}, parts...)...), nil
}

func writeCompletionFile(path string, content []byte) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}

	return os.WriteFile(path, content, 0o600)
}

func fileExists(path string) bool {
	if _, err := os.Stat(path); err == nil {
		return true
	}

	return false
}

func printCompletionInstallMessage(cmd *cli.Command, localizer output.Localizer, shell string, path string, existed bool) {
	localizer = output.EnsureLocalizer(localizer)

	action := localizer.Get("Installed")
	if existed {
		action = localizer.Get("Updated")
	}

	_, _ = fmt.Fprintln(cmd.ErrWriter, localizer.Get("%s %s completion at %s", action, shell, path))

	for _, line := range completionNextSteps(localizer, shell, path) {
		_, _ = fmt.Fprintln(cmd.ErrWriter, line)
	}

	for _, line := range completionBinaryNotes(localizer, completionAppName(cmd)) {
		_, _ = fmt.Fprintln(cmd.ErrWriter, line)
	}
}

func completionNextSteps(localizer output.Localizer, shell string, path string) []string {
	localizer = output.EnsureLocalizer(localizer)

	switch shell {
	case shellBash:
		return []string{
			localizer.Get("Reload your shell or run: source %s", path),
		}
	case shellZsh:
		return []string{
			localizer.Get("Ensure %s is in your fpath", filepath.Dir(path)),
			localizer.Get("Then run: autoload -Uz compinit && compinit"),
		}
	case shellFish:
		return []string{
			localizer.Get("Reload your shell or run: source %s", path),
		}
	default:
		return nil
	}
}

func completionBinaryNotes(localizer output.Localizer, appName string) []string {
	localizer = output.EnsureLocalizer(localizer)

	binaryName := filepath.Base(os.Args[0])
	if binaryName == appName && !strings.Contains(os.Args[0], "/") {
		return nil
	}

	return []string{
		localizer.Get("Completions are registered for '%s' (the binary name).", appName),
		localizer.Get("Ensure that name is on your PATH when invoking the command."),
	}
}

func completionRecoveryError(localizer output.Localizer, commandName string, cause error) error {
	localizer = output.EnsureLocalizer(localizer)
	shellList := strings.Join(completionShells(), ", ")

	msg := completionErrorMessage(localizer, cause)

	return commands.RecoveryError{
		Msg: msg,
		Suggestions: []string{
			localizer.Get("Available shells: %s", shellList),
			localizer.Get("Usage: %s completion <shell>|--all", commandName),
			localizer.Get("Run '%s completion --help' for more information", commandName),
		},
		Cause: cause,
	}
}

func completionErrorMessage(localizer output.Localizer, err error) output.LocaleMsg {
	if err == nil {
		return output.Msg("")
	}

	switch {
	case errors.Is(err, errCompletionMissingShell):
		return output.Msg(localizer.Get("missing shell for completion command"))
	case errors.Is(err, errCompletionAllExtraArgs):
		return output.Msg(localizer.Get("no extra arguments allowed with --all"))
	case errors.Is(err, errCompletionExtraArgs):
		return output.Msg(localizer.Get("exactly one shell argument is required"))
	case errors.Is(err, errCompletionOutput):
		return output.Msg(localizer.Get("failed to write completion output"))
	case errors.Is(err, errCompletionUnknownShell):
		if shellName := completionUnknownShellName(err); shellName != "" {
			return output.Msg(localizer.Get("unknown shell %s", shellName))
		}
	}

	return output.Msg(localizer.Get("shell completion failed: %s", err))
}

func completionUnknownShellName(err error) string {
	prefix := errCompletionUnknownShell.Error() + ": "
	if after, ok := strings.CutPrefix(err.Error(), prefix); ok {
		return after
	}

	return ""
}

func completionShells() []string {
	return []string{shellBash, shellZsh, shellFish}
}

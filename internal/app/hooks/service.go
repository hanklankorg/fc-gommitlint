// NewHooksPathRedirectError reports that a local install would write a hook
// git never runs, because core.hooksPath sends this repository's hooks to
// redirect. The path is carried for the recovery message.
func NewHooksPathRedirectError(hookType, redirect string) error {
	return hookError(ErrHooksPathRedirected, hookType, redirect, nil)
}

// DefaultHookTypes returns the locally managed hook types.
func DefaultHookTypes() []string {
	return []string{HookTypeCommitMsg, HookTypePrePush}
}

// FileInfo is the file metadata required by hook lifecycle policy.
type FileInfo interface {
	Mode() os.FileMode
	ModTime() time.Time
	Size() int64
}

// CheckFunc validates existing hook content before an atomic write.
type CheckFunc func(existingContent []byte) error

// Store provides filesystem operations required by hook lifecycle policy.
//
// Eight methods on one port, kept whole on purpose: the hook lifecycle is
// the only consumer and every install, verify and remove path uses the
// full set, so two ports would split one policy across two fakes. Split it
// when a second consumer needs a subset.
type Store interface {
	IsNotExist(err error) bool
	MkdirAll(path string, perm os.FileMode) error
	ReadDir(path string) ([]string, error)
	ReadFile(path string) ([]byte, error)
	Remove(path string) error
	RemoveWithCheck(path string, check CheckFunc) error
	Stat(path string) (FileInfo, error)
	WriteFileWithCheck(path string, data []byte, perm os.FileMode, check CheckFunc) error
}


// GlobalHookRemovalStatus represents removal status for a global hook type.
type GlobalHookRemovalStatus struct {
	HookType          string
	Found             bool
	Removed           bool
	ForeignDispatcher bool
	// ForeignPlugins lists plugin scripts gommitlint did not write. When
	// present, the dispatcher stays so those plugins keep running.
	ForeignPlugins []string
}

// GlobalRemovalResult contains global hook removal details.
type GlobalRemovalResult struct {
	HooksPath         string
	Hooks             []GlobalHookRemovalStatus
	ForeignHooks      []string
	Incomplete        bool
	HooksPathAction   PathAction
	RestoredHooksPath string
}

// AnyRemoved reports whether any gommitlint-managed global file was removed.
func (r GlobalRemovalResult) AnyRemoved() bool {
	for _, status := range r.Hooks {
		if status.Removed {
			return true
		}
	}

	return false
}

// ForeignPlugins returns every foreign plugin script left in place.
func (r GlobalRemovalResult) ForeignPlugins() []string {
	var plugins []string
	for _, status := range r.Hooks {
		plugins = append(plugins, status.ForeignPlugins...)
	}

	return plugins
}

// HasForeignContent reports whether changing core.hooksPath would disable files
// Gommitlint deliberately left in the global hooks directory.
func (r GlobalRemovalResult) HasForeignContent() bool {
	if len(r.ForeignHooks) > 0 || len(r.ForeignPlugins()) > 0 {
		return true
	}

	for _, status := range r.Hooks {
		if status.ForeignDispatcher {
			return true
		}
	}

	return false
}


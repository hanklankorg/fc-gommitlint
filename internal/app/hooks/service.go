// PathAction reports what a global install or removal did to the
// global git config key core.hooksPath.
type PathAction string

// PathAction values.
const (
	// HooksPathSet means core.hooksPath was empty and now names the gommitlint directory.
	HooksPathSet PathAction = "set"
	// HooksPathKept means core.hooksPath already named the gommitlint directory.
	HooksPathKept PathAction = "kept"
	// HooksPathReplaced means a foreign core.hooksPath was overwritten with --force.
	HooksPathReplaced PathAction = "replaced"
	// HooksPathUnset means core.hooksPath named the gommitlint directory and was unset.
	HooksPathUnset PathAction = "unset"
	// HooksPathRestored means core.hooksPath was reset to the value a forced install replaced.
	HooksPathRestored PathAction = "restored"
	// HooksPathUntouched means core.hooksPath was left as it was: it was unset,
	// it names a directory gommitlint does not own, or foreign plugins still
	// depend on the gommitlint dispatcher.
	HooksPathUntouched PathAction = "untouched"
)


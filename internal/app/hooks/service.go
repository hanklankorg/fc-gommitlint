// HookError adds hook context while preserving sentinel errors for errors.Is.
type HookError struct {
	HookType string
	Path     string
	Err      error
	Cause    error
}

func (e HookError) Error() string {
	if e.Cause != nil {
		return fmt.Sprintf("%s: %s", e.Err, e.Cause)
	}

	if e.Path != "" {
		return fmt.Sprintf("%s: %s", e.Err, e.Path)
	}

	return e.Err.Error()
}

func (e HookError) Unwrap() []error {
	if e.Cause == nil {
		return []error{e.Err}
	}

	return []error{e.Err, e.Cause}
}

// Install installs one local hook with overwrite safeguards.
func (s Service) Install(req InstallRequest) (InstallResult, error) {
	ctx, err := s.prepareLocalHook(req.RepoPath, req.HookType, true)
	if err != nil {
		return InstallResult{}, err
	}

	previousContent := ""
	wasOverwritten := false
	check := managedHookOverwriteCheck(req.HookType, ctx.hookPath, req.Force, IsManagedLocalHook, func(existingContent string) {
		previousContent = existingContent
		wasOverwritten = true
	})

	if err := s.Store.WriteFileWithCheck(ctx.hookPath, []byte(req.Script), 0o755, check); err != nil {
		return InstallResult{}, hookError(ErrWriteHook, req.HookType, ctx.hookPath, err)
	}

	return InstallResult{
		RepoPath:        ctx.validatedPath,
		HookPath:        ctx.hookPath,
		HookType:        req.HookType,
		FileSize:        int64(len(req.Script)),
		WasOverwritten:  wasOverwritten,
		PreviousContent: previousContent,
	}, nil
}

// PreflightInstall verifies that one local hook may be installed without
// mutating the repository.
func (s Service) PreflightInstall(req InstallRequest) error {
	ctx, err := s.prepareLocalHook(req.RepoPath, req.HookType, false)
	if err != nil {
		return err
	}

	if s.Local.ValidateInstallTarget != nil {
		if err := s.Local.ValidateInstallTarget(ctx.validatedPath); err != nil {
			return err
		}
	}

	existingContent, err := s.Store.ReadFile(ctx.hookPath)
	if err != nil {
		if s.Store.IsNotExist(err) {
			return nil
		}

		return hookError(ErrStatHook, req.HookType, ctx.hookPath, err)
	}

	check := managedHookOverwriteCheck(req.HookType, ctx.hookPath, req.Force, IsManagedLocalHook, nil)

	return check(existingContent)
}

// Remove removes one local hook only when gommitlint generated it.
func (s Service) Remove(req RemovalRequest) (RemovalResult, error) {
	inspection, err := s.InspectRemoval(req)
	if err != nil {
		return RemovalResult{}, err
	}

	if !inspection.Exists {
		return RemovalResult{
			RepoPath: inspection.RepoPath,
			HookType: inspection.HookType,
		}, nil
	}

	if !inspection.IsGommitlint {
		return RemovalResult{}, hookError(ErrNotGommitlintHook, req.HookType, inspection.HookPath, nil)
	}

	previousContent := inspection.Content
	removeCheck := func(existingContent []byte) error {
		if !IsManagedLocalHook(string(existingContent)) {
			return ErrNotGommitlintHook
		}

		previousContent = string(existingContent)

		return nil
	}

	if err := s.Store.RemoveWithCheck(inspection.HookPath, removeCheck); err != nil {
		if errors.Is(err, ErrNotGommitlintHook) {
			return RemovalResult{}, hookError(ErrNotGommitlintHook, req.HookType, inspection.HookPath, err)
		}

		return RemovalResult{}, hookError(ErrRemoveHook, req.HookType, inspection.HookPath, err)
	}

	return RemovalResult{
		RepoPath:        inspection.RepoPath,
		HookPath:        inspection.HookPath,
		HookType:        inspection.HookType,
		WasGommitlint:   inspection.IsGommitlint,
		PreviousSize:    int64(len(previousContent)),
		PreviousContent: previousContent,
	}, nil
}

// InspectRemoval reports what local hook removal would do without mutating files.
func (s Service) InspectRemoval(req RemovalRequest) (RemovalInspection, error) {
	ctx, err := s.prepareLocalHook(req.RepoPath, req.HookType, false)
	if err != nil {
		return RemovalInspection{}, err
	}

	fileInfo, err := s.Store.Stat(ctx.hookPath)
	if s.Store.IsNotExist(err) {
		return RemovalInspection{
			RepoPath: ctx.validatedPath,
			HookPath: ctx.hookPath,
			HookType: req.HookType,
			Exists:   false,
		}, nil
	}

	if err != nil {
		return RemovalInspection{}, hookError(ErrStatHook, req.HookType, ctx.hookPath, err)
	}

	content, err := s.Store.ReadFile(ctx.hookPath)
	if err != nil {
		return RemovalInspection{}, hookError(ErrHookNotFound, req.HookType, ctx.hookPath, err)
	}

	contentString := string(content)

	return RemovalInspection{
		RepoPath:     ctx.validatedPath,
		HookPath:     ctx.hookPath,
		HookType:     req.HookType,
		Exists:       true,
		Size:         fileInfo.Size(),
		Content:      contentString,
		IsGommitlint: IsManagedLocalHook(contentString),
		ModifiedTime: fileInfo.ModTime(),
		IsExecutable: fileInfo.Mode()&0o111 != 0,
	}, nil
}

// Status gets local hook status for a repository, plus global hook visibility.
func (s Service) Status(ctx context.Context, repoPath string) (RepositoryStatus, error) {
	if err := ctx.Err(); err != nil {
		return RepositoryStatus{}, err
	}

	if err := validateStatusDependencies(s); err != nil {
		return RepositoryStatus{}, err
	}

	validatedPath, err := s.Local.ValidateRepository(repoPath)
	if err != nil {
		return RepositoryStatus{}, hookError(ErrInvalidRepository, "", "", err)
	}

	if err := ctx.Err(); err != nil {
		return RepositoryStatus{}, err
	}

	hookNames := DefaultHookTypes()

	hookPaths, err := resolveStatusPaths(s, validatedPath, hookNames)
	if err != nil {
		return RepositoryStatus{}, err
	}

	primaryPath := firstStatusPath(hookPaths)
	effectiveHooksPath := primaryPath.HooksDir

	hooksPathRedirected := false
	if s.Local.ResolveHooksPath != nil {
		effectiveHooksPath, hooksPathRedirected, err = s.Local.ResolveHooksPath(ctx, validatedPath)
		if err != nil {
			return RepositoryStatus{}, err
		}
	}

	globalHooksPath, err := s.configuredHooksPath(ctx)
	if err != nil {
		return RepositoryStatus{}, hookError(ErrGlobalHooksPathUnavailable, "", "", err)
	}

	if err := ctx.Err(); err != nil {
		return RepositoryStatus{}, err
	}

	if _, err := s.Store.Stat(primaryPath.HooksDir); err != nil {
		if !s.Store.IsNotExist(err) {
			return RepositoryStatus{}, hookError(ErrStatHook, "", primaryPath.HooksDir, err)
		}

		if globalHooksPath == "" {
			return RepositoryStatus{
				RepoPath:            validatedPath,
				GitDir:              primaryPath.GitDir,
				HooksDir:            primaryPath.HooksDir,
				GlobalHooksPath:     globalHooksPath,
				EffectiveHooksPath:  effectiveHooksPath,
				HooksPathRedirected: hooksPathRedirected,
				Hooks:               []HookStatus{},
			}, nil
		}
	}

	statuses, err := hookStatuses(ctx, s, hookNames, hookPaths, globalHooksPath)
	if err != nil {
		return RepositoryStatus{}, err
	}

	if err := ctx.Err(); err != nil {
		return RepositoryStatus{}, err
	}

	return RepositoryStatus{
		RepoPath:            validatedPath,
		GitDir:              primaryPath.GitDir,
		HooksDir:            primaryPath.HooksDir,
		GlobalHooksPath:     globalHooksPath,
		EffectiveHooksPath:  effectiveHooksPath,
		HooksPathRedirected: hooksPathRedirected,
		Hooks:               statuses,
	}, nil
}

func resolveStatusPaths(service Service, repoPath string, hookNames []string) ([]RepositoryHookPath, error) {
	paths := make([]RepositoryHookPath, 0, len(hookNames))

	for _, hookName := range hookNames {
		path, err := service.Local.ResolveStatusPath(repoPath, hookName)
		if err != nil {
			return nil, err
		}

		paths = append(paths, path)
	}

	return paths, nil
}

func firstStatusPath(paths []RepositoryHookPath) RepositoryHookPath {
	if len(paths) == 0 {
		return RepositoryHookPath{}
	}

	return paths[0]
}

func validateStatusDependencies(service Service) error {
	if service.Local.ValidateRepository == nil {
		return ErrRepositoryValidatorRequired
	}

	if service.Store == nil {
		return ErrStoreRequired
	}

	if service.Local.ResolveStatusPath == nil {
		return ErrHookPathResolverRequired
	}

	return nil
}

func hookStatuses(ctx context.Context, service Service, hookNames []string, paths []RepositoryHookPath, globalHooksPath string) ([]HookStatus, error) {
	statuses := make([]HookStatus, 0, len(hookNames))

	for index, hookName := range hookNames {
		if err := ctx.Err(); err != nil {
			return nil, err
		}

		localHookPath, err := hookPathForStatus(paths, index, hookName)
		if err != nil {
			return nil, err
		}

		status, err := service.HookStatus(hookName, localHookPath, globalHookStatusPath(globalHooksPath, hookName))
		if err != nil {
			return nil, err
		}

		statuses = append(statuses, status)
	}

	return statuses, nil
}

func globalHookStatusPath(globalHooksPath string, hookName string) string {
	if globalHooksPath == "" {
		return ""
	}

	return GlobalHookPluginScriptPath(globalHooksPath, hookName)
}

func hookPathForStatus(paths []RepositoryHookPath, index int, hookName string) (string, error) {
	if index >= len(paths) {
		return "", hookError(ErrHookPathResolverRequired, hookName, "", nil)
	}

	hookPath := strings.TrimSpace(paths[index].LocalPath)
	if hookPath == "" {
		return "", hookError(ErrHookPathResolverRequired, hookName, "", nil)
	}

	return hookPath, nil
}

// HookStatus gets status for a single hook from local and optional global paths.
func (s Service) HookStatus(name, localPath, globalPath string) (HookStatus, error) {
	local, err := s.inspectHookFile(name, localPath, IsManagedLocalHook)
	if err != nil {
		return HookStatus{}, err
	}

	global, err := s.inspectHookFile(name, globalPath, IsManagedGlobalHook)
	if err != nil {
		return HookStatus{}, err
	}

	return HookStatus{Name: name, Local: local, Global: global}, nil
}

// InstallGlobal installs global hook dispatchers and gommitlint plugins.
//
// core.hooksPath is only claimed when it is unset or already names the
// gommitlint directory. A foreign value is refused unless req.Force is set,
// in which case the previous value is recorded so RemoveGlobal can restore it.
func (s Service) InstallGlobal(ctx context.Context, req GlobalInstallRequest) (GlobalInstallResult, error) {
	if err := ctx.Err(); err != nil {
		return GlobalInstallResult{}, err
	}

	hooksPath, err := s.resolveGlobalHooksPath(ctx)
	if err != nil {
		return GlobalInstallResult{}, err
	}

	if err := s.validateGlobalInstallDependencies(); err != nil {
		return GlobalInstallResult{}, err
	}

	current, err := s.configuredHooksPath(ctx)
	if err != nil {
		return GlobalInstallResult{}, hookError(ErrGlobalHooksPathUnavailable, "", "", err)
	}

	action, err := planHooksPathClaim(current, hooksPath, req.Force)
	if err != nil {
		return GlobalInstallResult{}, err
	}

	if err := ctx.Err(); err != nil {
		return GlobalInstallResult{}, err
	}

	hookTypes, files, err := s.planGlobalInstallFiles(hooksPath, current, action, req)
	if err != nil {
		return GlobalInstallResult{}, err
	}

	applied, err := s.applyGlobalInstallFiles(ctx, files, req.Force)
	if err != nil {
		return GlobalInstallResult{}, err
	}

	result := GlobalInstallResult{HooksPath: hooksPath, HookTypes: hookTypes, HooksPathAction: action}

	switch action {
	case HooksPathKept:
		if err := ctx.Err(); err != nil {
			return GlobalInstallResult{}, errors.Join(err, s.rollbackGlobalInstall(applied))
		}

		return result, nil
	case HooksPathReplaced:
		result.PreviousHooksPath = current
	case HooksPathSet, HooksPathUnset, HooksPathRestored, HooksPathUntouched:
	}

	if err := ctx.Err(); err != nil {
		return GlobalInstallResult{}, errors.Join(err, s.rollbackGlobalInstall(applied))
	}

	if err := s.Global.SetGlobalHooksPath(ctx, hooksPath); err != nil {
		cause := hookError(ErrConfigureGlobalHooks, "", hooksPath, err)

		return GlobalInstallResult{}, errors.Join(cause, s.rollbackGlobalInstall(applied))
	}

	return result, nil
}

// planHooksPathClaim decides how an install may take core.hooksPath.
func planHooksPathClaim(current string, hooksPath string, force bool) (PathAction, error) {
	switch {
	case current == "":
		return HooksPathSet, nil
	case sameHooksPath(current, hooksPath):
		return HooksPathKept, nil
	case force:
		return HooksPathReplaced, nil
	default:
		return "", hookError(ErrHooksPathInUse, "", current, nil)
	}
}

func sameHooksPath(left string, right string) bool {
	return filepath.Clean(strings.TrimSpace(left)) == filepath.Clean(strings.TrimSpace(right))
}

// RemoveGlobalWithStatus removes gommitlint-managed global hook files and
// returns per-hook status plus what happened to core.hooksPath.
//
// A dispatcher whose plugin directory still holds foreign scripts is kept, so
// those scripts keep running. core.hooksPath is only changed when it names the
// gommitlint directory and no dispatcher had to stay: it is restored to the
// value a forced install replaced, or unset otherwise.
func (s Service) RemoveGlobalWithStatus(ctx context.Context) (GlobalRemovalResult, error) {
	if err := ctx.Err(); err != nil {
		return GlobalRemovalResult{}, err
	}

	hooksPath, err := s.resolveGlobalHooksPath(ctx)
	if err != nil {
		return GlobalRemovalResult{}, err
	}

	if s.Store == nil {
		return GlobalRemovalResult{}, ErrStoreRequired
	}

	result := GlobalRemovalResult{HooksPath: hooksPath, HooksPathAction: HooksPathUntouched}
	hookTypes := DefaultHookTypes()

	configuredPath, err := s.configuredHooksPath(ctx)
	if err != nil {
		return GlobalRemovalResult{}, hookError(ErrGlobalHooksPathUnavailable, "", "", err)
	}

	hooksPathExists, err := s.globalHooksPathExists(hooksPath)
	if err != nil {
		return GlobalRemovalResult{}, err
	}

	if !hooksPathExists {
		result.Hooks = globalHookStatusesNotFound(hookTypes)
	} else {
		result.ForeignHooks, err = s.foreignGlobalHooks(hooksPath)
		if err != nil {
			return GlobalRemovalResult{}, err
		}

		result.Hooks, err = s.removeGlobalHooks(ctx, hooksPath, hookTypes)
		if err != nil {
			result.Incomplete = true

			return result, err
		}
	}

	if result.HasForeignContent() || !sameHooksPath(configuredPath, hooksPath) {
		if err := ctx.Err(); err != nil {
			return result, err
		}

		return result, nil
	}

	if err := ctx.Err(); err != nil {
		return result, err
	}

	action, restored, err := s.releaseHooksPath(ctx, hooksPath)
	if err != nil {
		result.Incomplete = true

		return result, err
	}

	result.HooksPathAction = action
	result.RestoredHooksPath = restored

	return result, nil
}

func (s Service) validateGlobalInstallDependencies() error {
	if s.Store == nil {
		return ErrStoreRequired
	}

	if s.Global.SetGlobalHooksPath == nil {
		return ErrGlobalGitConfigSetterRequired
	}

	return nil
}

func (s Service) globalHooksPathExists(hooksPath string) (bool, error) {
	_, err := s.Store.Stat(hooksPath)
	if err == nil {
		return true, nil
	}

	if s.Store.IsNotExist(err) {
		return false, nil
	}

	return false, hookError(ErrStatHook, "", hooksPath, err)
}

func (s Service) removeGlobalHooks(ctx context.Context, hooksPath string, hookTypes []string) ([]GlobalHookRemovalStatus, error) {
	statuses := make([]GlobalHookRemovalStatus, 0, len(hookTypes))

	for _, hookType := range hookTypes {
		if err := ctx.Err(); err != nil {
			return statuses, err
		}

		status, err := s.removeGlobalHook(hooksPath, hookType)
		if err != nil {
			return statuses, err
		}

		statuses = append(statuses, status)
	}

	return statuses, nil
}

func (s Service) configuredHooksPath(ctx context.Context) (string, error) {
	if s.Global.ConfiguredHooksPath == nil {
		return "", nil
	}

	path, err := s.Global.ConfiguredHooksPath(ctx)
	if err != nil {
		return "", err
	}

	return strings.TrimSpace(path), nil
}

// releaseHooksPath restores or unsets a core.hooksPath that names hooksPath.
func (s Service) releaseHooksPath(ctx context.Context, hooksPath string) (PathAction, string, error) {
	markerPath := filepath.Join(hooksPath, previousHooksPathFile)

	previous, err := s.Store.ReadFile(markerPath)
	if err != nil && !s.Store.IsNotExist(err) {
		return "", "", hookError(ErrHookNotFound, "", markerPath, err)
	}

	restored := strings.TrimSpace(string(previous))
	if restored != "" {
		if s.Global.SetGlobalHooksPath == nil {
			return "", "", ErrGlobalGitConfigSetterRequired
		}

		if err := s.Global.SetGlobalHooksPath(ctx, restored); err != nil {
			return "", "", hookError(ErrConfigureGlobalHooks, "", restored, err)
		}

		if err := s.Store.Remove(markerPath); err != nil && !s.Store.IsNotExist(err) {
			return "", "", hookError(ErrRemoveHook, "", markerPath, err)
		}

		return HooksPathRestored, restored, nil
	}

	if s.Global.UnsetGlobalHooksPath == nil {
		return HooksPathUntouched, "", nil
	}

	if err := s.Global.UnsetGlobalHooksPath(ctx); err != nil {
		return "", "", hookError(ErrConfigureGlobalHooks, "", hooksPath, err)
	}

	if err := s.Store.Remove(markerPath); err != nil && !s.Store.IsNotExist(err) {
		return "", "", hookError(ErrRemoveHook, "", markerPath, err)
	}

	return HooksPathUnset, "", nil
}

// GlobalHookDispatcherPath returns the dispatcher path under a global hooks root.
func GlobalHookDispatcherPath(hooksPath string, hookType string) string {
	return filepath.Join(hooksPath, hookType)
}

// GlobalHookPluginPath returns the plugin directory path under a global hooks root.
func GlobalHookPluginPath(hooksPath string, hookType string) string {
	return filepath.Join(hooksPath, hookType+".d")
}

// GlobalHookPluginScriptPath returns the gommitlint plugin path under a global hooks root.
func GlobalHookPluginScriptPath(hooksPath string, hookType string) string {
	return filepath.Join(GlobalHookPluginPath(hooksPath, hookType), globalPluginFile)
}

// IsManagedLocalHook reports whether local hook content was generated by gommitlint.
func IsManagedLocalHook(content string) bool {
	for line := range strings.SplitSeq(content, "\n") {
		line = strings.TrimSpace(line)
		if line == "# "+generatedHookMarker || line == "# "+generatedLocalHookMarker+"." {
			return true
		}

		if version, found := strings.CutPrefix(line, "# "+generatedHookMarker+" v"); found && version != "" && !strings.ContainsAny(version, " \t") {
			return true
		}
	}

	return false
}

// IsManagedGlobalHook reports whether global hook content was generated by gommitlint.
func IsManagedGlobalHook(content string) bool {
	for line := range strings.SplitSeq(content, "\n") {
		line = strings.TrimSpace(line)
		if line == "# "+generatedGlobalByMarker || line == "# "+generatedGlobalHookMarker {
			return true
		}

		for _, hookType := range DefaultHookTypes() {
			if line == "# "+hookType+" "+globalDispatcherMarker {
				return true
			}
		}
	}

	return false
}

func (s Service) resolveGlobalHooksPath(ctx context.Context) (string, error) {
	if s.Global.ResolveGlobalHooksPath == nil {
		return "", ErrGlobalHooksPathRequired
	}

	hooksPath := strings.TrimSpace(s.Global.ResolveGlobalHooksPath(ctx))
	if hooksPath == "" {
		return "", ErrGlobalHooksPathUnavailable
	}

	return hooksPath, nil
}

func globalHookTypes(hookTypes []string) []string {
	if len(hookTypes) == 0 {
		return DefaultHookTypes()
	}

	result := make([]string, len(hookTypes))
	copy(result, hookTypes)

	return result
}

type globalInstallFile struct {
	hookType     string
	path         string
	content      []byte
	mode         os.FileMode
	previous     []byte
	previousMode os.FileMode
	existed      bool
	managed      bool
}

func (s Service) planGlobalInstallFiles(hooksPath, current string, action PathAction, req GlobalInstallRequest) ([]string, []globalInstallFile, error) {
	hookTypes := globalHookTypes(req.HookTypes)

	files, err := s.planGlobalInstall(hooksPath, hookTypes, req.Force)
	if err != nil {
		return nil, nil, err
	}

	if action != HooksPathReplaced {
		return hookTypes, files, nil
	}

	markerPath := filepath.Join(hooksPath, previousHooksPathFile)

	marker, err := s.planGlobalInstallFile("", markerPath, []byte(current+"\n"), 0o600, false, req.Force)
	if err != nil {
		return nil, nil, err
	}

	return hookTypes, append(files, marker), nil
}

func (s Service) applyGlobalInstallFiles(ctx context.Context, files []globalInstallFile, force bool) ([]globalInstallFile, error) {
	applied := make([]globalInstallFile, 0, len(files))

	for _, file := range files {
		if err := ctx.Err(); err != nil {
			return nil, errors.Join(err, s.rollbackGlobalInstall(applied))
		}

		if err := s.Store.MkdirAll(filepath.Dir(file.path), 0o755); err != nil {
			cause := hookError(ErrCreateHookDirectory, file.hookType, filepath.Dir(file.path), err)

			return nil, errors.Join(cause, s.rollbackGlobalInstall(applied))
		}

		var check CheckFunc
		if file.managed {
			check = managedHookOverwriteCheck(file.hookType, file.path, force, IsManagedGlobalHook, nil)
		}

		if err := s.Store.WriteFileWithCheck(file.path, file.content, file.mode, check); err != nil {
			cause := hookError(ErrWriteHook, file.hookType, file.path, err)

			return nil, errors.Join(cause, s.rollbackGlobalInstall(applied))
		}

		applied = append(applied, file)
	}

	return applied, nil
}

func (s Service) planGlobalInstall(hooksPath string, hookTypes []string, force bool) ([]globalInstallFile, error) {
	if s.Global.DispatcherScript == nil || s.Global.PluginScript == nil {
		return nil, ErrGlobalScriptProviderRequired
	}

	files := make([]globalInstallFile, 0, len(hookTypes)*2)
	for _, hookType := range hookTypes {
		dispatcherPath := GlobalHookDispatcherPath(hooksPath, hookType)

		dispatcher, err := s.planGlobalInstallFile(hookType, dispatcherPath, []byte(s.Global.DispatcherScript(hookType)), 0o755, true, force)
		if err != nil {
			return nil, err
		}

		files = append(files, dispatcher)

		pluginScript, err := s.Global.PluginScript(hookType)
		if err != nil {
			return nil, err
		}

		pluginPath := GlobalHookPluginScriptPath(hooksPath, hookType)

		plugin, err := s.planGlobalInstallFile(hookType, pluginPath, []byte(pluginScript), 0o755, true, force)
		if err != nil {
			return nil, err
		}

		files = append(files, plugin)
	}

	return files, nil
}

func (s Service) planGlobalInstallFile(hookType string, path string, content []byte, mode os.FileMode, managed bool, force bool) (globalInstallFile, error) {
	file := globalInstallFile{hookType: hookType, path: path, content: content, mode: mode, managed: managed}

	existingContent, err := s.Store.ReadFile(path)
	if err != nil {
		if s.Store.IsNotExist(err) {
			return file, nil
		}

		return globalInstallFile{}, hookError(ErrHookNotFound, hookType, path, err)
	}

	file.existed = true

	file.previous = append([]byte(nil), existingContent...)

	fileInfo, err := s.Store.Stat(path)
	if err != nil {
		return globalInstallFile{}, hookError(ErrStatHook, hookType, path, err)
	}

	file.previousMode = fileInfo.Mode()

	if managed {
		if err := managedHookOverwriteCheck(hookType, path, force, IsManagedGlobalHook, nil)(existingContent); err != nil {
			return globalInstallFile{}, err
		}
	}

	return file, nil
}

func (s Service) rollbackGlobalInstall(applied []globalInstallFile) error {
	var rollbackErrors []error

	for _, file := range slices.Backward(applied) {
		unchanged := func(current []byte) error {
			if !bytes.Equal(current, file.content) {
				return errGlobalInstallChanged
			}

			return nil
		}

		var err error
		if file.existed {
			err = s.Store.WriteFileWithCheck(file.path, file.previous, file.previousMode, unchanged)
		} else {
			err = s.Store.RemoveWithCheck(file.path, unchanged)
			if s.Store.IsNotExist(err) {
				err = nil
			}
		}

		if err != nil {
			rollbackErrors = append(rollbackErrors, fmt.Errorf("rollback %s: %w", file.path, err))
		}
	}

	return errors.Join(rollbackErrors...)
}

func managedHookOverwriteCheck(hookType string, path string, force bool, isManaged func(string) bool, onExisting func(string)) CheckFunc {
	return func(existingContent []byte) error {
		if existingContent == nil {
			return nil
		}

		content := string(existingContent)
		if onExisting != nil {
			onExisting(content)
		}

		if !isManaged(content) {
			return hookError(ErrCustomHookExists, hookType, path, nil)
		}

		if !force {
			return hookError(ErrHookAlreadyExists, hookType, path, nil)
		}

		return nil
	}
}

func globalHookStatusesNotFound(hookTypes []string) []GlobalHookRemovalStatus {
	statuses := make([]GlobalHookRemovalStatus, 0, len(hookTypes))
	for _, hookType := range hookTypes {
		statuses = append(statuses, GlobalHookRemovalStatus{HookType: hookType})
	}

	return statuses
}

func (s Service) removeGlobalHook(hooksPath string, hookType string) (GlobalHookRemovalStatus, error) {
	status := GlobalHookRemovalStatus{HookType: hookType}
	pluginDir := GlobalHookPluginPath(hooksPath, hookType)

	pluginFound, pluginRemoved, err := s.removeManagedGlobalFile(hookType, GlobalHookPluginScriptPath(hooksPath, hookType))
	if err != nil {
		return GlobalHookRemovalStatus{}, err
	}

	foreign, err := s.foreignPlugins(hookType, pluginDir)
	if err != nil {
		return GlobalHookRemovalStatus{}, err
	}

	status.ForeignPlugins = foreign

	if len(foreign) > 0 {
		// The dispatcher is what runs those plugins; removing it would
		// silently disable tools gommitlint does not own.
		status.Found = true
		status.Removed = pluginRemoved

		return status, nil
	}

	if pluginRemoved {
		_ = s.Store.Remove(pluginDir)
	}

	dispatcherFound, dispatcherRemoved, err := s.removeManagedGlobalFile(hookType, GlobalHookDispatcherPath(hooksPath, hookType))
	if err != nil {
		return GlobalHookRemovalStatus{}, err
	}

	status.Found = pluginFound || dispatcherFound
	status.Removed = pluginRemoved || dispatcherRemoved
	status.ForeignDispatcher = dispatcherFound && !dispatcherRemoved

	return status, nil
}

func (s Service) foreignGlobalHooks(hooksPath string) ([]string, error) {
	entries, err := s.Store.ReadDir(hooksPath)
	if err != nil {
		if s.Store.IsNotExist(err) {
			return nil, nil
		}

		return nil, hookError(ErrStatHook, "", hooksPath, err)
	}

	managedNames := map[string]struct{}{
		previousHooksPathFile: {},
		".gommitlint.lock":    {},
	}
	for _, hookType := range DefaultHookTypes() {
		managedNames[hookType] = struct{}{}
		managedNames[hookType+".d"] = struct{}{}
	}

	var foreign []string

	for _, name := range entries {
		if _, managed := managedNames[name]; !managed {
			foreign = append(foreign, filepath.Join(hooksPath, name))
		}
	}

	return foreign, nil
}

// foreignPlugins lists plugin scripts in pluginDir that gommitlint did not write.
func (s Service) foreignPlugins(hookType string, pluginDir string) ([]string, error) {
	entries, err := s.Store.ReadDir(pluginDir)
	if err != nil {
		if s.Store.IsNotExist(err) {
			return nil, nil
		}

		return nil, hookError(ErrStatHook, hookType, pluginDir, err)
	}

	var foreign []string

	for _, name := range entries {
		if name == globalPluginFile || !strings.HasSuffix(name, ".sh") {
			continue
		}

		foreign = append(foreign, filepath.Join(pluginDir, name))
	}

	return foreign, nil
}

func (s Service) removeManagedGlobalFile(hookType string, path string) (bool, bool, error) {
	content, err := s.Store.ReadFile(path)
	if err != nil {
		if s.Store.IsNotExist(err) {
			return false, false, nil
		}

		return false, false, hookError(ErrHookNotFound, hookType, path, err)
	}

	if !IsManagedGlobalHook(string(content)) {
		return true, false, nil
	}

	err = s.Store.RemoveWithCheck(path, func(existingContent []byte) error {
		if !IsManagedGlobalHook(string(existingContent)) {
			return ErrNotGommitlintHook
		}

		return nil
	})
	if err != nil {
		switch {
		case errors.Is(err, ErrNotGommitlintHook):
			return true, false, nil
		case s.Store.IsNotExist(err):
			return true, true, nil
		default:
			return true, false, hookError(ErrRemoveHook, hookType, path, err)
		}
	}

	return true, true, nil
}

type localHookContext struct {
	validatedPath string
	hookPath      string
}

func (s Service) prepareLocalHook(repoPath, hookType string, ensureHooksDir bool) (localHookContext, error) {
	if err := s.validateLocalHookDependencies(ensureHooksDir); err != nil {
		return localHookContext{}, err
	}

	validatedPath, err := s.Local.ValidateRepository(repoPath)
	if err != nil {
		return localHookContext{}, hookError(ErrInvalidRepository, hookType, "", err)
	}

	if ensureHooksDir {
		if s.Local.ValidateInstallTarget != nil {
			if err := s.Local.ValidateInstallTarget(validatedPath); err != nil {
				return localHookContext{}, err
			}
		}

		if err := s.Local.EnsureHooksDirectory(validatedPath); err != nil {
			return localHookContext{}, err
		}
	}

	hookPath, err := s.Local.FindHookPath(validatedPath, hookType)
	if err != nil {
		return localHookContext{}, err
	}

	if err := s.Local.ValidatePathInRepo(validatedPath, hookPath); err != nil {
		return localHookContext{}, hookError(ErrPathOutsideRepository, hookType, hookPath, err)
	}

	return localHookContext{validatedPath: validatedPath, hookPath: hookPath}, nil
}

func (s Service) validateLocalHookDependencies(ensureHooksDir bool) error {
	if s.Local.ValidateRepository == nil {
		return ErrRepositoryValidatorRequired
	}

	if s.Local.FindHookPath == nil {
		return ErrHookPathResolverRequired
	}

	if s.Local.ValidatePathInRepo == nil {
		return ErrPathContainmentRequired
	}

	if s.Store == nil {
		return ErrStoreRequired
	}

	if ensureHooksDir && s.Local.EnsureHooksDirectory == nil {
		return ErrHooksDirectoryEnsurerRequired
	}

	return nil
}

func (s Service) inspectHookFile(name, path string, isManaged func(string) bool) (HookFileStatus, error) {
	status := HookFileStatus{Path: path}
	if path == "" {
		return status, nil
	}

	fileInfo, err := s.Store.Stat(path)
	if err != nil {
		if s.Store.IsNotExist(err) {
			return status, nil
		}

		return HookFileStatus{}, hookError(ErrStatHook, name, path, err)
	}

	status.Exists = true
	applyHookFileInfo(&status, fileInfo)

	content, err := s.Store.ReadFile(path)
	if err != nil {
		return HookFileStatus{}, hookError(ErrHookNotFound, name, path, err)
	}

	status.Content = string(content)
	status.IsGommitlint = isManaged(status.Content)

	return status, nil
}

func applyHookFileInfo(status *HookFileStatus, fileInfo FileInfo) {
	status.ModifiedTime = fileInfo.ModTime()
	status.Size = fileInfo.Size()
	status.IsExecutable = fileInfo.Mode()&0o111 != 0
}

func hookError(err error, hookType, path string, cause error) error {
	return HookError{
		HookType: hookType,
		Path:     path,
		Err:      err,
		Cause:    cause,
	}
}

// TestService_LocalHookOperations_RefusePathOutsideRepository pins the
// containment refusal for every local operation that resolves a hook path: the
// error names the refusal and its cause, and the existing hook is untouched.
func TestService_LocalHookOperations_RefusePathOutsideRepository(t *testing.T) {
	t.Parallel()

	installRequest := InstallRequest{Force: true, HookType: HookTypeCommitMsg, RepoPath: testRepoPath, Script: "new script"}
	removalRequest := RemovalRequest{HookType: HookTypeCommitMsg, RepoPath: testRepoPath}

	for _, testCase := range []struct {
		name string
		run  func(Service) error
	}{
		{name: "install", run: func(s Service) error {
			_, err := s.Install(installRequest)

			return err
		}},
		{name: "preflight_install", run: func(s Service) error { return s.PreflightInstall(installRequest) }},
		{name: "remove", run: func(s Service) error {
			_, err := s.Remove(removalRequest)

			return err
		}},
		{name: "inspect_removal", run: func(s Service) error {
			_, err := s.InspectRemoval(removalRequest)

			return err
		}},
	} {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			store := managedHookStore()
			service := newTestService(store)
			service.Local.ValidatePathInRepo = func(string, string) error { return errTestPathOutsideRepository }

			err := testCase.run(service.Service)

			check.ErrorIs(t, err, ErrPathOutsideRepository)
			check.ErrorIs(t, err, errTestPathOutsideRepository)
			check.Equal(t, "# Generated by gommitlint", string(store.files[testCommitMsgPath].content))
			check.Len(t, store.files, 1)
		})
	}
}

func TestService_Install_RefusesCustomHookEvenWithForce(t *testing.T) {
	t.Parallel()

	store := newTestStore()
	store.files[testCommitMsgPath] = testFile{content: []byte("#!/bin/sh\necho custom"), mode: 0o755}
	service := newTestService(store)

	_, err := service.Install(InstallRequest{
		Force:    true,
		HookType: HookTypeCommitMsg,
		RepoPath: testRepoPath,
		Script:   "new script",
	})

	check.ErrorIs(t, err, ErrCustomHookExists)
	check.Equal(t, "#!/bin/sh\necho custom", string(store.files[testCommitMsgPath].content))
	// The mode is part of "unchanged" for a hook: a refusal that rewrote it
	// could leave the operator's hook non-executable.
	check.Equal(t, fs.FileMode(0o755), store.files[testCommitMsgPath].mode)
	// And nothing was written anywhere else — a refusal that put the new script
	// at a different path would satisfy every assertion above.
	check.Len(t, store.files, 1)
}


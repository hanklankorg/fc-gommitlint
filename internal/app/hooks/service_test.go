func (s *testStore) MkdirAll(path string, _ os.FileMode) error {
	s.dirs[path] = true

	return nil
}

func (s *testStore) IsNotExist(err error) bool {
	return errors.Is(err, os.ErrNotExist)
}

func (s *testStore) ReadDir(path string) ([]string, error) {
	if !s.dirs[path] {
		return nil, os.ErrNotExist
	}

	var names []string

	for filePath := range s.files {
		if dir, name := filepath.Split(filePath); filepath.Clean(dir) == path {
			names = append(names, name)
		}
	}

	slices.Sort(names)

	return names, nil
}

func (s *testStore) ReadFile(path string) ([]byte, error) {
	file, ok := s.files[path]
	if !ok {
		return nil, os.ErrNotExist
	}

	return file.content, nil
}

func (s *testStore) Remove(path string) error {
	if _, ok := s.files[path]; ok {
		delete(s.files, path)

		return nil
	}

	if _, ok := s.dirs[path]; ok {
		delete(s.dirs, path)

		return nil
	}

	return os.ErrNotExist
}

func (s *testStore) RemoveWithCheck(path string, check CheckFunc) error {
	if s.beforeCheckedRemove != nil {
		s.beforeCheckedRemove()
		s.beforeCheckedRemove = nil
	}

	file, ok := s.files[path]
	if !ok {
		return os.ErrNotExist
	}

	if check != nil {
		if err := check(file.content); err != nil {
			return err
		}
	}

	delete(s.files, path)

	return nil
}

func (s *testStore) Stat(path string) (FileInfo, error) {
	file, ok := s.files[path]
	if !ok {
		if s.dirs[path] {
			return testFileInfo{file: testFile{mode: 0o755}}, nil
		}

		return nil, os.ErrNotExist
	}

	return testFileInfo{file: file}, nil
}

func (s *testStore) WriteFileWithCheck(path string, data []byte, perm os.FileMode, check CheckFunc) error {
	var existingContent []byte
	if file, ok := s.files[path]; ok {
		existingContent = file.content
	}

	if check != nil {
		if err := check(existingContent); err != nil {
			return err
		}
	}

	s.files[path] = testFile{content: data, mode: perm, modTime: time.Now()}

	return nil
}

type testFileInfo struct {
	file testFile
}

func (i testFileInfo) Mode() os.FileMode {
	return i.file.mode
}

func (i testFileInfo) ModTime() time.Time {
	return i.file.modTime
}

func (i testFileInfo) Size() int64 {
	return int64(len(i.file.content))
}

// A forced reinstall over managed files the user has edited must, when the
// git config update fails, put every file back with its previous content and
// mode rather than deleting it.
func TestService_InstallGlobal_RollbackRestoresFilesThatExistedBefore(t *testing.T) {
	t.Parallel()

	store := newTestStore()
	service := newTestService(store)

	_, err := service.InstallGlobal(t.Context(), GlobalInstallRequest{})
	check.NoError(t, err)

	before := make(map[string]testFile, len(store.files))

	for path, file := range store.files {
		edited := testFile{content: append([]byte("# edited\n"), file.content...), mode: 0o700}
		store.files[path] = edited
		before[path] = edited
	}

	// core.hooksPath was unset in the meantime, so the reinstall has to claim it
	// again and the failing git config write is what triggers the rollback.
	service.configuredGlobalPath = ""
	service.Global.SetGlobalHooksPath = func(context.Context, string) error { return errTestGitConfigWrite }

	_, err = service.InstallGlobal(t.Context(), GlobalInstallRequest{Force: true})

	check.ErrorIs(t, err, errTestGitConfigWrite)
	check.Len(t, store.files, len(before))

	for path, want := range before {
		got, exists := store.files[path]
		check.True(t, exists, "%s must be restored, not deleted", path)
		check.Equal(t, string(want.content), string(got.content), "content of %s", path)
		check.Equal(t, want.mode, got.mode, "mode of %s", path)
	}
}

func TestService_RemoveGlobal_RemovesOnlyManagedGlobalFiles(t *testing.T) {
	t.Parallel()

	store := newTestStore()
	service := newTestService(store)
	_, err := service.InstallGlobal(t.Context(), GlobalInstallRequest{})
	check.NoError(t, err)

	// The "only" half of this test's name had nothing to stand on: the store
	// contained nothing but gommitlint's own files, so removing all of them
	// satisfied it. These two bystanders are what an operator actually has in a
	// global hooks directory — a hook for a type gommitlint does not manage,
	// and an unrelated file — and deleting either would be data loss.
	const (
		foreignHook   = testGlobalPath + "/pre-commit"
		unrelatedFile = testGlobalPath + "/README"
	)

	store.files[foreignHook] = testFile{content: []byte("#!/bin/sh\necho mine\n"), mode: 0o755}
	store.files[unrelatedFile] = testFile{content: []byte("notes\n"), mode: 0o644}

	result, err := service.RemoveGlobalWithStatus(t.Context())

	check.NoError(t, err)
	check.Len(t, result.Hooks, 2)
	check.Equal(t, GlobalHookRemovalStatus{HookType: HookTypeCommitMsg, Found: true, Removed: true}, result.Hooks[0])
	check.Equal(t, GlobalHookRemovalStatus{HookType: HookTypePrePush, Found: true, Removed: true}, result.Hooks[1])
	check.NotContains(t, store.files, GlobalHookPluginScriptPath(testGlobalPath, HookTypeCommitMsg))
	check.NotContains(t, store.files, GlobalHookDispatcherPath(testGlobalPath, HookTypePrePush))
	check.Equal(t, HooksPathUntouched, result.HooksPathAction)
	check.False(t, service.unsetGlobalPath)
	check.Equal(t, []string{unrelatedFile, foreignHook}, result.ForeignHooks)

	check.Equal(t, "#!/bin/sh\necho mine\n", string(store.files[foreignHook].content))
	check.Equal(t, "notes\n", string(store.files[unrelatedFile].content))
	check.Len(t, store.files, 2)
}


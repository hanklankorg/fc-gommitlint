type testStore struct {
	dirs                map[string]bool
	files               map[string]testFile
	beforeCheckedRemove func()
}

type testFile struct {
	content []byte
	mode    os.FileMode
	modTime time.Time
}

type statusErrorStore struct {
	*testStore

	statErr  error
	readErr  error
	readPath string
}

func managedHookStore() *testStore {
	store := newTestStore()
	store.dirs[testRepoPath+"/.git/hooks"] = true
	store.files[testCommitMsgPath] = testFile{content: []byte("# Generated by gommitlint"), mode: 0o755}

	return store
}

func (s *statusErrorStore) Stat(path string) (FileInfo, error) {
	if path == testCommitMsgPath && s.statErr != nil {
		return nil, s.statErr
	}

	return s.testStore.Stat(path)
}

func (s *statusErrorStore) ReadFile(path string) ([]byte, error) {
	readPath := s.readPath
	if readPath == "" {
		readPath = testCommitMsgPath
	}

	if path == readPath && s.readErr != nil {
		return nil, s.readErr
	}

	return s.testStore.ReadFile(path)
}


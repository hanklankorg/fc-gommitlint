func TestPrintConfigInitYAML_ProducesValidYAML(t *testing.T) {
	t.Parallel()

	// Create a temporary file for testing
	tmpFile, err := os.CreateTemp(t.TempDir(), "config-init-test-*.yaml")
	check.NoError(t, err)

	defer func() {
		_ = tmpFile.Close()
		_ = os.Remove(tmpFile.Name())
	}()

	// Create default config
	defaultCfg := configuration.NewConfigWithDefaults()

	// Test the function that ExecuteConfigInit calls
	err = printConfigInitYAML(defaultCfg, tmpFile, nil)
	check.NoError(t, err, "should print config YAML without error")

	// Read back the content
	_, err = tmpFile.Seek(0, 0)
	check.NoError(t, err)

	content := make([]byte, 10240)
	n, _ := tmpFile.Read(content)
	result := string(content[:n])

	check.NotEmpty(t, result, "should produce output")

	// Parse the YAML to ensure it's valid (remove comments first)
	yamlLines := strings.Split(result, "\n")

	var yamlWithoutComments []string

	for _, line := range yamlLines {
		if !strings.HasPrefix(strings.TrimSpace(line), "#") && strings.TrimSpace(line) != "" {
			yamlWithoutComments = append(yamlWithoutComments, line)
		}
	}

	cleanYAML := strings.Join(yamlWithoutComments, "\n")

	var parsedConfig map[string]any

	err = yaml.Unmarshal([]byte(cleanYAML), &parsedConfig)
	check.NoError(t, err, "output should be valid YAML")

	check.Contains(t, parsedConfig, "gommitlint", "should contain gommitlint root")
}

type failOnceConfigWriter struct {
	bytes.Buffer

	failed bool
}

func (writer *failOnceConfigWriter) Write(content []byte) (int, error) {
	if !writer.failed {
		writer.failed = true

		return 0, errMockWrite
	}

	return writer.Buffer.Write(content)
}

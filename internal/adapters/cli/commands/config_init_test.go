func TestWriteConfigInitFile_RefusesToOverwriteWithoutForce(t *testing.T) {
	localizer := testLocalizer(t, "en")

	t.Chdir(t.TempDir())

	render := func(writer io.Writer) error {
		_, err := io.WriteString(writer, "rendered configuration\n")

		return err
	}

	check.NoError(t, writeConfigInitFile(configInitDestination{path: "created.yaml"}, localizer, render),
		"a missing file must be created")

	created, err := os.ReadFile("created.yaml")
	check.NoError(t, err)
	check.Equal(t, "rendered configuration\n", string(created))

	const existing = "existing configuration\n"
	check.NoError(t, os.WriteFile("config.yaml", []byte(existing), 0o600))

	err = writeConfigInitFile(configInitDestination{path: "config.yaml"}, localizer, render)
	check.ErrorIs(t, err, os.ErrExist)

	var recovery RecoveryError
	check.ErrorAs(t, err, &recovery)
	check.Contains(t, recovery.Suggestions, "Overwrite: gommitlint config init --force")

	content, readErr := os.ReadFile("config.yaml")
	check.NoError(t, readErr)
	check.Equal(t, existing, string(content), "the refusal must leave the existing file unchanged")
}

func TestConfigInit_RefusesSymlinkedParentIntoGitDirWithoutChanges(t *testing.T) {
	repo := t.TempDir()
	t.Chdir(repo)

	gitDir := filepath.Join(repo, ".git")
	markerPath := filepath.Join(gitDir, "config")

	const marker = "[core]\n"

	check.NoError(t, os.Mkdir(gitDir, 0o750))
	check.NoError(t, os.WriteFile(markerPath, []byte(marker), 0o600))
	check.NoError(t, os.Symlink(gitDir, filepath.Join(repo, "alias")))

	cmd := createTestConfigCommand(commandNameConfigInit, io.Discard)
	cmd.Flags = []cli.Flag{
		&cli.BoolFlag{Name: flagNameStdout},
		&cli.StringFlag{Name: flagNameOutput},
		&cli.StringFlag{Name: flagNamePreset},
		&cli.BoolFlag{Name: flagNameForce},
	}
	check.NoError(t, cmd.Set(flagNameOutput, filepath.Join("alias", "gommitlint.yaml")))

	err := ExecuteConfigInit(t.Context(), cmd)

	check.ErrorIs(t, err, fileops.ErrSymlinkNotAllowed)

	_, statErr := os.Lstat(filepath.Join(gitDir, "gommitlint.yaml"))
	check.True(t, errors.Is(statErr, os.ErrNotExist), "refusal must not create a file in .git")

	content, readErr := os.ReadFile(markerPath)
	check.NoError(t, readErr)
	check.Equal(t, marker, string(content))

	entries, readErr := os.ReadDir(gitDir)
	check.NoError(t, readErr)
	check.Len(t, entries, 1)
	check.Equal(t, "config", entries[0].Name())
}


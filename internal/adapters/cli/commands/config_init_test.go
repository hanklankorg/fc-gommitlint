// Only a path element that is exactly ".git" (in any case) marks the git
// directory. Names that merely start or end with it, such as ".github" or a
// repository called "legit.git", are ordinary directories.
func TestIsInsideGitDir_MatchesOnlyAGitPathElement(t *testing.T) {
	t.Parallel()

	tests := []struct {
		path string
		want bool
	}{
		{path: filepath.Join("repo", ".git", "config.yaml"), want: true},
		{path: filepath.Join("repo", ".GIT", "config.yaml"), want: true},
		{path: filepath.Join("repo", ".GiT", "config.yaml"), want: true},
		{path: filepath.Join("repo", ".github", "config.yaml"), want: false},
		{path: filepath.Join("legit.git", "config.yaml"), want: false},
		{path: filepath.Join("repo", "x.git"), want: false},
	}

	for _, testCase := range tests {
		t.Run(testCase.path, func(t *testing.T) {
			t.Parallel()

			check.Equal(t, testCase.want, isInsideGitDir(testCase.path))
		})
	}
}


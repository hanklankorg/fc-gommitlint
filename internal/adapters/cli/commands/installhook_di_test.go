const testGitConfig = "[core]\n\trepositoryformatversion = 0\n"

// setupGitRepoInFS sets up a git repository structure using FileSystem abstraction.
func setupGitRepoInFS(t *testing.T, fs *testhelpers.FileSystem, repoPath string) {
	t.Helper()

	// Create .git directory structure
	gitDir := filepath.Join(repoPath, ".git")
	fs.CreateDir(gitDir)

	// Create hooks directory
	hooksDir := filepath.Join(gitDir, "hooks")
	fs.CreateDir(hooksDir)

	// Create config file
	configPath := filepath.Join(gitDir, "config")
	fs.WriteFile(configPath, []byte(testGitConfig))
}

func TestInstallSingleHookWithFS_InstallsGuardsAndOverwrites(t *testing.T) {
	t.Parallel()

	t.Run("install hook in empty repository", func(t *testing.T) {
		t.Parallel()

		// Use real filesystem with t.TempDir() for isolation
		// Note: Memory filesystem can't be used here because ValidateGitRepository
		// uses filepath.Abs() which always checks the real OS filesystem
		fs := testhelpers.NewFileSystem(t)
		repoPath := fs.Path("test-repo")

		// Create the repo directory first
		fs.CreateDir(repoPath)

		// Set up git repository structure
		setupGitRepoInFS(t, fs, repoPath)

		// Create Afero adapter for the signing package
		aferoAdapter := signing.NewAferoAdapter(fs.GetAferoFS())

		// Test installation with DI
		result, err := installSingleHookWithFS(t.Context(), aferoAdapter, false, repoPath, hookTypeCommitMsg, createCommitMsgHookScript(), nil)
		check.NoError(t, err)
		check.Equal(t, repoPath, result.RepoPath)
		check.Contains(t, result.HookPath, "commit-msg")
		check.False(t, result.WasOverwritten)

		// Verify hook was created
		hookPath := filepath.Join(repoPath, ".git", "hooks", "commit-msg")
		check.True(t, fs.FileExists(hookPath))

		content := fs.ReadFile(hookPath)
		check.Contains(t, content, "gommitlint")
		check.Contains(t, content, "Generated by gommitlint")

		// Verify hook is executable (check file mode in metadata)
		info := fs.StatFile(hookPath)
		check.Equal(t, uint32(0o755), uint32(info.Mode().Perm()))
	})

	t.Run("prevent overwriting custom hook without force", func(t *testing.T) {
		t.Parallel()

		// Use real filesystem with t.TempDir() for isolation
		fs := testhelpers.NewFileSystem(t)
		repoPath := fs.Path("test-repo")

		// Create the repo directory first
		fs.CreateDir(repoPath)

		// Set up git repository structure
		setupGitRepoInFS(t, fs, repoPath)

		// Create existing custom hook
		hookPath := filepath.Join(repoPath, ".git", "hooks", "commit-msg")
		customHookContent := "#!/bin/bash\n# Custom hook\necho 'Custom validation'"
		fs.WriteExecutable(hookPath, []byte(customHookContent))

		// Create Afero adapter
		aferoAdapter := signing.NewAferoAdapter(fs.GetAferoFS())

		// Try to install without force - should fail
		_, err := installSingleHookWithFS(t.Context(), aferoAdapter, false, repoPath, hookTypeCommitMsg, createCommitMsgHookScript(), nil)
		check.Error(t, err)
		check.ErrorIs(t, err, ErrCustomHookExists)

		// Verify original hook is unchanged
		content := fs.ReadFile(hookPath)
		check.Equal(t, customHookContent, content)
	})

	t.Run("overwrite gommitlint hook with force", func(t *testing.T) {
		t.Parallel()

		// Use real filesystem with t.TempDir() for isolation
		fs := testhelpers.NewFileSystem(t)
		repoPath := fs.Path("test-repo")

		// Create the repo directory first
		fs.CreateDir(repoPath)

		// Set up git repository structure
		setupGitRepoInFS(t, fs, repoPath)

		// Create existing gommitlint hook (old version)
		hookPath := filepath.Join(repoPath, ".git", "hooks", "commit-msg")
		oldHookContent := "#!/bin/bash\n# Generated by gommitlint v1.0\nold content"
		fs.WriteExecutable(hookPath, []byte(oldHookContent))

		// Create Afero adapter
		aferoAdapter := signing.NewAferoAdapter(fs.GetAferoFS())

		// Install with force - should succeed
		result, err := installSingleHookWithFS(t.Context(), aferoAdapter, true, repoPath, hookTypeCommitMsg, createCommitMsgHookScript(), nil)
		check.NoError(t, err)
		check.True(t, result.WasOverwritten)
		check.Equal(t, oldHookContent, result.PreviousContent)

		// Verify hook was updated
		content := fs.ReadFile(hookPath)
		check.NotEqual(t, oldHookContent, content)
		check.Contains(t, content, "Generated by gommitlint")
	})

	t.Run("handle permission errors gracefully", func(t *testing.T) {
		// Skip this test on Windows where chmod doesn't work the same way
		if runtime.GOOS == "windows" {
			t.Skip("Skipping permission test on Windows")
		}

		// Skip if running as root (root can write to read-only directories)
		if os.Geteuid() == 0 {
			t.Skip("Skipping permission test when running as root")
		}

		t.Parallel()

		// For permission testing, we need a real filesystem
		fs := testhelpers.NewFileSystem(t)
		repoPath := fs.Path("test-repo")

		// Set up git repository structure
		setupGitRepoInFS(t, fs, repoPath)

		// Make hooks directory read-only
		hooksDir := filepath.Join(repoPath, ".git", "hooks")
		fs.ChmodDir(hooksDir, 0o555)

		// Ensure we restore permissions for cleanup
		defer func() {
			fs.ChmodDir(hooksDir, 0o755)
		}()

		// Create Afero adapter for real filesystem
		aferoAdapter := signing.NewAferoAdapter(fs.GetAferoFS())

		// Try to install - should fail due to permissions
		_, err := installSingleHookWithFS(t.Context(), aferoAdapter, false, repoPath, hookTypeCommitMsg, createCommitMsgHookScript(), nil)
		check.Error(t, err)
		// The error message will vary by OS, but it should be a permission error
		// We just check that installation failed
	})
}
